export type Bucket = {
  house?: string;
  verdict: string;
  good: string[];
  mixed: string[];
  bad: string[];
  suit: string[];
  avoid: string[];
  events: string[];
  notes: string[];
};

type Sec = "good" | "mixed" | "bad" | "suit" | "avoid" | "events";
const HEADER = /^(ดี|ระวัง|กลาง|ผสม|เหมาะกับ|ไม่เหมาะกับ|มุมให้คุณ|มุมให้โทษ|เหตุการณ์ในเดือนนี้[^:]*):\s*(.*)$/;
const SEC_OF: Record<string, Sec> = {
  ดี: "good",
  มุมให้คุณ: "good",
  ระวัง: "bad",
  มุมให้โทษ: "bad",
  กลาง: "mixed",
  ผสม: "mixed",
  เหมาะกับ: "suit",
  ไม่เหมาะกับ: "avoid",
};

export function bucketize(item: Pick<Item, "head" | "text" | "tone" | "sub">): Bucket {
  const b: Bucket = { verdict: "", good: [], mixed: [], bad: [], suit: [], avoid: [], events: [], notes: [] };
  const add = (arr: string[], s: string) => {
    if (s && !PLACEHOLDERS.has(s) && !arr.includes(s)) arr.push(s);
  };
  let sec: Sec | null = null;

  for (const raw of item.sub ?? []) {
    const line = raw.trim().replace(/^[•\-*\s]+/, "");
    if (!line) continue;
    const h = line.match(HEADER);
    let body = line;
    if (h) {
      sec = h[1].startsWith("เหตุการณ์") ? "events" : SEC_OF[h[1]];
      body = h[2].trim();
      if (!body) continue;
    }
    const tag = body.match(/^\[(ดี|ร้าย|ผสม)\]/)?.[1];
    const target: Sec | "notes" = tag
      ? tag === "ดี"
        ? "good"
        : tag === "ร้าย"
          ? "bad"
          : "mixed"
      : sec ?? "notes";
    const kindHint: Tone | undefined = target === "good" ? "ดี" : target === "bad" ? "ร้าย" : target === "mixed" ? "ผสม" : undefined;
    const parts = h && (h[1] === "มุมให้คุณ" || h[1] === "มุมให้โทษ") ? body.split(" · ") : [body];
    for (const p of parts) {
      const { text } = plainLine(p, kindHint);
      if (target === "notes") {
        if (!/^คำนวณจาก/.test(text)) add(b.notes, text);
      } else add(b[target], text);
    }
  }

  const house = houseFromText(`${item.head ?? ""} ${item.text ?? ""}`);
  if (house && HOUSE_VOICE[house]) {
    const v = HOUSE_VOICE[house];
    b.house = house;
    b.verdict =
      item.tone === "ดี" ? v.good : item.tone === "ร้าย" ? v.bad : item.tone === "ผสม" ? v.mixed : `เกี่ยวข้องกับเรื่อง${v.topic}`;
    if (item.tone !== "ร้าย") add(b.suit, v.doIt);
    if (item.tone !== "ดี") add(b.avoid, v.avoid);
  }
  return b;
}

export const hasContent = (b: Bucket) => b.good.length + b.mixed.length + b.bad.length + b.suit.length + b.avoid.length > 0;