export function houseFromText(s: string): string | undefined {
  const m = s.match(/ภพ\s*\d*\s*(ลัคนา|กฎุมพะ|สหัชชะ|พันธุ|ปุตตะ|อริ|ปัตนิ|มรณะ|ศุภะ|กัมมะ|ลาภะ|วินาศนะ)/);
  return m?.[1];
}

