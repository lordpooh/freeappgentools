const SUIT_DAYS: Record<Suit, number> = { wands: 1, swords: 7, cups: 14, pentacles: 30 };
const COURT_UNITS = [2, 1, 4, 5]; // เพจ ไนท์ ควีน คิง

// เมเจอร์: เร็ว = 5 วัน, กลาง = 45 วัน, ช้า = 120 วัน
const MAJOR_DAYS = [
  5, 5, 45, 45, 45, 45, 45, 5, 45, 120, 5,
  45, 120, 5, 45, 120, 5, 45, 120, 5, 45, 120,
];

function baseDays(c: DrawnCard): number {
  let d: number;
  if (c.card.arcana === "major") {
    d = MAJOR_DAYS[c.card.id];
  } else {
    const r = rankOf(c);
    const units = r <= 9 ? r + 1 : COURT_UNITS[r - 10];
    d = SUIT_DAYS[c.card.suit as Suit] * units;
  }
  return c.reversed ? d * 1.5 : d;
}

function humanize(d: number): string {
  const n = Math.max(1, Math.round(d));
  if (n <= 2) return "ภายใน 1–2 วัน";
  if (n < 14) return `ราว ${n} วัน`;
  if (n < 60) return `ราว ${Math.round(n / 7)} สัปดาห์`;
  if (n < 730) return `ราว ${Math.round(n / 30)} เดือน`;
  return `ราว ${Math.round(n / 365)} ปี`;
}

function dateRange(now: Date, d: number): string {
  const lo = Math.max(1, Math.round(d * 0.7));
  const hi = Math.max(lo + 1, Math.round(d * 1.4));
  const add = (n: number) => {
    const x = new Date(now);
    x.setDate(x.getDate() + n);
    return x.toLocaleDateString("th-TH", { day: "numeric", month: "short", year: "numeric" });
  };
  return `${add(lo)} – ${add(hi)}`;
}

/* ───────────── ตัวช่วย ───────────── */

const nm = (c: DrawnCard) => `${c.card.name}${c.reversed ? " (กลับหัว)" : ""}`;
const src = (c: DrawnCard) => `${nm(c)} · ${c.position.replace(/^\d+\.\s*/, "")}`;
const rankOf = (c: DrawnCard) => (c.card.arcana === "minor" ? (c.card.id - 22) % 14 : -1);
const isCourt = (c: DrawnCard) => rankOf(c) >= 10;

function dominantSuit(cards: DrawnCard[]): Suit | undefined {
  const count: Partial<Record<Suit, number>> = {};
  for (const c of cards) if (c.card.suit) count[c.card.suit] = (count[c.card.suit] ?? 0) + 1;
  let best: Suit | undefined;
  let max = 0;
  for (const [s, n] of Object.entries(count) as [Suit, number][]) {
    if (n > max) {
      max = n;
      best = s;
    }
  }
  return best;
}

function findPerson(cards: DrawnCard[], order: number[]): DrawnCard | null {
  for (const i of order) if (cards[i] && isCourt(cards[i])) return cards[i];
  for (const i of order) {
    const c = cards[i];
    if (c && c.card.arcana === "major" && PERSON_MAJOR[c.card.id]) return c;
  }
  return null;
}

/* ───────────── ฟังก์ชันหลัก ───────────── */

export function readOpportunity(r: SpreadResult, now: Date = new Date()): OpportunityReading {
  const cards = r.cards;
  const four = r.kind === "four";
  const iOut = cards.length - 1;
  const iNear = four ? 2 : 5;
  const iObs = 1;
  const iAdv = four ? 2 : 4;
  // ลำดับไพ่ที่ใช้หา "บุคคล" (ข้ามตำแหน่ง "ตัวคุณ" และ "ความหวัง/ความกลัว" ในไพ่ 10 ใบ)
  const personOrder = four ? [3, 2, 0, 1] : [7, 9, 5, 4, 2, 3, 0, 1];

  const key = cards[iOut];
  const near = cards[iNear];
  const keySuit = key.card.suit as Suit | undefined;

  // โอกาสเกิดขึ้นมากแค่ไหน
  const lean =
    SCORE[key.tone] * 2 + SCORE[near.tone] + SCORE[cards[iAdv].tone] * 0.5 + SCORE[cards[iObs].tone] * 0.5;
  const level: OpportunityReading["level"] = lean >= 1.5 ? "สูง" : lean <= -1 ? "ต่ำ" : "ปานกลาง";
  const levelNote =
    level === "สูง"
      ? "ไพ่ผลลัพธ์และไพ่อนาคตโน้มไปทางบวก โอกาสนี้มีแนวโน้มเข้ามาจริงหากคุณพร้อมรับ"
      : level === "ปานกลาง"
        ? "โอกาสมีอยู่ แต่ยังขึ้นกับการตัดสินใจและการลงมือของคุณ"
        : "ไพ่ยังมีอุปสรรคหรือโน้มลบ โอกาสอาจยังไม่มาในรอบนี้ หรือมาพร้อมเงื่อนไข ควรแก้เรื่องที่ติดค้างก่อน";

  const rows: OppRow[] = [];

  // 1) โอกาสแบบไหน
  rows.push({
    key: "type",
    icon: "🎯",
    label: "โอกาสแบบไหน",
    value: keySuit ? OPP[keySuit][r.topic] : MAJOR_OPP[key.card.id],
    sub:
      key.tone === "ระวัง"
        ? `ไพ่ผลลัพธ์ค่อนไปทางลบ โอกาสนี้อาจมาพร้อมความเสี่ยง ควรตรวจสอบก่อนตอบรับ · ความหมายไพ่: ${key.meaning}`
        : `ความหมายไพ่: ${key.meaning}`,
    from: src(key),
  });

  // 2) ใคร + 3) ลักษณะ
  const person = findPerson(cards, personOrder);
  if (person && isCourt(person)) {
    const rk = rankOf(person) - 10;
    const ps = person.card.suit as Suit;
    rows.push({
      key: "who",
      icon: "👤",
      label: "ใคร",
      value: RANK_ROLE[rk],
      from: src(person),
    });
    rows.push({
      key: "trait",
      icon: "✨",
      label: "ลักษณะ",
      value: SUIT_TRAIT[ps],
      sub: person.reversed ? `ด้านที่ต้องระวัง (ไพ่กลับหัว): ${RANK_REV_NOTE[rk]}` : undefined,
      from: src(person),
    });
  } else if (person) {
    rows.push({
      key: "who",
      icon: "👤",
      label: "ใคร",
      value: PERSON_MAJOR[person.card.id],
      from: src(person),
    });
    rows.push({
      key: "trait",
      icon: "✨",
      label: "ลักษณะ",
      value: `บุคลิกตามความหมายไพ่: ${person.meaning}`,
      from: src(person),
    });
  } else {
    rows.push({
      key: "who",
      icon: "👤",
      label: "ใคร",
      value: "ยังไม่มีบุคคลเด่นในไพ่ โอกาสน่าจะมาจากตัวคุณเอง หรือจากสถานการณ์/ระบบ ไม่ใช่คนใดคนหนึ่งโดยเฉพาะ",
      from: "ไม่พบไพ่บุคคล (เพจ ไนท์ ควีน คิง)",
    });
    rows.push({
      key: "trait",
      icon: "✨",
      label: "ลักษณะ",
      value: `ลักษณะของโอกาส: ${key.meaning}`,
      from: src(key),
    });
  }

  // 4) สถานที่
  const env = four ? null : cards[7];
  rows.push({
    key: "place",
    icon: "📍",
    label: "สถานที่ไหน",
    value: keySuit ? SUIT_PLACE[keySuit] : MAJOR_PLACE[key.card.id],
    sub:
      env && env.card.id !== key.card.id
        ? `สภาพแวดล้อม (${nm(env)}): ${env.card.suit ? SUIT_PLACE[env.card.suit as Suit] : MAJOR_PLACE[env.card.id]}`
        : undefined,
    from: src(key),
  });

  // 5) เวลา (ช่วงของวัน/ฤดู)
  const seasonSuit = keySuit ?? dominantSuit(cards);
  rows.push({
    key: "time",
    icon: "🕐",
    label: "เวลาอะไร",
    value: `ช่วงเวลาในวัน: ${keySuit ? SUIT_TOD[keySuit] : MAJOR_TOD[key.card.id]}`,
    sub: seasonSuit ? `ช่วงของปี (ตามตำรา): ${SUIT_SEASON[seasonSuit]}` : undefined,
    from: src(key),
  });

  // 6) เมื่อไหร่
  const dOut = baseDays(key);
  const dNear = baseDays(near);
  rows.push({
    key: "when",
    icon: "📅",
    label: "เมื่อไหร่",
    value: `${humanize(dOut)} (ประมาณ ${dateRange(now, dOut)})`,
    sub: `สัญญาณแรก (${nm(near)}): ${humanize(dNear)}${
      key.reversed ? " · ไพ่ผลลัพธ์กลับหัว อาจช้ากว่าที่ประเมิน ต้องแก้อุปสรรคก่อน" : ""
    }`,
    from: src(key),
  });

  return { level, levelNote, rows };
}